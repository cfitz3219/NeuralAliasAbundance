<#
.SYNOPSIS
  Regenerates src/host_dx12/sl_proxy/sl_proxy_exports.inl from one or more real
  Streamline interposer DLLs (C5, reconstructed 2026-10; original lost in the crash).

.DESCRIPTION
  Reads each DLL's PE export table directly (no dumpbin / VS environment needed),
  takes the UNION of the exported names, and writes one linker pragma per name:
      #pragma comment(linker, "/export:NAME=sl_interposer_real.NAME")
  i.e. a PE forwarder to the renamed original. Names given in -Exclude are NOT
  forwarded; each gets a comment line instead, because sl_proxy.cpp implements
  it as a typed wrapper. (A .def file is not used: MSVC's def parser exported
  local symbols instead of forwarders - see WORKLOG-ROUTE-A A3.)

.EXAMPLE
  ./scripts/generate-sl-proxy-def.ps1 `
     -Inputs 'D:\TLOU I\sl.interposer.dll=1.4.7.0 (TLOU I)','D:\TLOU II\sl.interposer.dll=2.7.2.0 (TLOU II)' `
     -Exclude @{ slInit='typed wrapper in sl_proxy.cpp' }
#>
[CmdletBinding()]
param(
    # "path" or "path=label" (label shown in the header comment).
    [Parameter(Mandatory)] [string[]] $Inputs,
    # name -> reason; these names become comments instead of forwarders.
    [hashtable] $Exclude = @{
        slInit                = 'typed wrapper in sl_proxy.cpp'
        slEvaluateFeature     = 'preserves explicit frame/viewport through synchronous NGX call'
        slGetFeatureSettings  = 'typed wrapper in sl_proxy.cpp (A71 observation)'
        slSetConstants        = 'pinned-layout observation wrapper in sl_proxy.cpp'
        slSetFeatureConstants = 'typed wrapper in sl_proxy.cpp (A71 observation)'
    },
    [string] $Output = [IO.Path]::Combine($PSScriptRoot, '..', 'src', 'host_dx12', 'sl_proxy', 'sl_proxy_exports.inl'),
    [string] $Target = 'sl_interposer_real'
)
$ErrorActionPreference = 'Stop'

function Get-ExportNames([string] $Path) {
    $b = [System.IO.File]::ReadAllBytes($Path)
    if ([BitConverter]::ToUInt16($b, 0) -ne 0x5A4D) { throw "$Path is not a PE file (no MZ)" }
    $pe = [BitConverter]::ToInt32($b, 0x3C)
    if ([BitConverter]::ToUInt32($b, $pe) -ne 0x00004550) { throw "$Path has no PE signature" }
    $coff = $pe + 4
    $sections = [BitConverter]::ToUInt16($b, $coff + 2)
    $optSize = [BitConverter]::ToUInt16($b, $coff + 16)
    $opt = $coff + 20
    $magic = [BitConverter]::ToUInt16($b, $opt)
    $ddOffset = if ($magic -eq 0x20B) { 112 } elseif ($magic -eq 0x10B) { 96 } else { throw "${Path}: unknown optional header" }
    $expRva = [BitConverter]::ToUInt32($b, $opt + $ddOffset)
    if ($expRva -eq 0) { return @() }
    $secTable = $opt + $optSize
    $toOffset = {
        param($rva)
        for ($i = 0; $i -lt $sections; $i++) {
            $s = $secTable + 40 * $i
            $va = [BitConverter]::ToUInt32($b, $s + 12)
            $size = [Math]::Max([BitConverter]::ToUInt32($b, $s + 8), [BitConverter]::ToUInt32($b, $s + 16))
            if ($rva -ge $va -and $rva -lt $va + $size) { return [int]($rva - $va + [BitConverter]::ToUInt32($b, $s + 20)) }
        }
        throw "RVA 0x{0:X} outside all sections" -f $rva
    }
    $exp = & $toOffset $expRva
    $count = [BitConverter]::ToUInt32($b, $exp + 24)
    $namesRva = [BitConverter]::ToUInt32($b, $exp + 32)
    $names = & $toOffset $namesRva
    $out = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $count; $i++) {
        $p = & $toOffset ([BitConverter]::ToUInt32($b, $names + 4 * $i))
        $end = $p; while ($b[$end] -ne 0) { $end++ }
        $out.Add([System.Text.Encoding]::ASCII.GetString($b, $p, $end - $p))
    }
    return $out
}

$labels = @()
$all = New-Object 'System.Collections.Generic.SortedSet[string]' ([StringComparer]::Ordinal)
foreach ($spec in $Inputs) {
    $path, $label = $spec -split '=', 2
    if (-not (Test-Path -LiteralPath $path)) { throw "Input not found: $path" }
    if (-not $label) { $label = (Get-Item -LiteralPath $path).VersionInfo.FileVersion }
    $labels += $label
    foreach ($n in (Get-ExportNames $path)) { [void]$all.Add($n) }
}

$forwarded = @($all | Where-Object { -not $Exclude.ContainsKey($_) })
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("// Generated by scripts/generate-sl-proxy-def.ps1 from sl.interposer.dll $($labels -join ' + ')$(if ($labels.Count -gt 1) {' (union)'})")
$lines.Add("// $($forwarded.Count) forwarded exports as linker /export pragmas (PE forwarders).")
$lines.Add('// Do not hand-edit; typed wrappers replace lines only via reviewed source changes.')
foreach ($k in ($Exclude.Keys | Sort-Object)) { if ($all.Contains($k)) { $lines.Add("// ${k}: $($Exclude[$k])") } }
foreach ($n in $forwarded) {
    if ($n -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { Write-Warning "skipping non-identifier export '$n'"; continue }
    $lines.Add("#pragma comment(linker, `"/export:$n=$Target.$n`")")
}
$outFull = [System.IO.Path]::GetFullPath($Output)
[System.IO.File]::WriteAllLines($outFull, $lines)
Write-Host "Wrote $($forwarded.Count) forwarders (+$(($Exclude.Keys | Where-Object { $all.Contains($_) }).Count) wrapped) to $Output"
